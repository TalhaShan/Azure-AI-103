import os
from pathlib import Path
from playsound3 import playsound
from dotenv import load_dotenv

# Import namespaces
# AzureOpenAI: OpenAI SDK client that talks to Azure OpenAI / Foundry models
from openai import AzureOpenAI
# DefaultAzureCredential: signs in with your Azure login (e.g. `az login`)
# get_bearer_token_provider: turns that login into tokens the client can send
from azure.identity import DefaultAzureCredential, get_bearer_token_provider


def main():
    try:
        # Clear the console
        os.system('cls' if os.name == 'nt' else 'clear')

        # Get Configuration Settings
        load_dotenv()
        endpoint=os.getenv("MODEL_ENDPOINT")
        model_deployment=os.getenv("MODEL_NAME")
        speech_file_path = Path(__file__).parent / "speech.mp3"


        # Create the Azure OpenAI client
        # Uses your Azure sign-in instead of an API key, so no secret is stored.
        # Your account needs a role such as "Cognitive Services OpenAI User"
        # on the resource.
        token_provider = get_bearer_token_provider(
            DefaultAzureCredential(),
            "https://cognitiveservices.azure.com/.default",
        )
        client = AzureOpenAI(
            azure_endpoint=endpoint,
            azure_ad_token_provider=token_provider,
            api_version="2025-03-01-preview",
        )


        # Generate speech and save to file
        # model is the name of your text-to-speech deployment (e.g. gpt-4o-mini-tts).
        # voice picks the speaker, input is the text to read aloud, and
        # instructions (supported by gpt-4o-mini-tts) controls the tone.
        # with_streaming_response lets us write the audio to the file as it arrives.
        text = "Hello! This speech was generated by an AI model running in Microsoft Foundry."
        with client.audio.speech.with_streaming_response.create(
            model=model_deployment,
            voice="alloy",
            input=text,
            instructions="Speak in a cheerful and positive tone.",
        ) as response:
            response.stream_to_file(speech_file_path)

        print(f"Speech saved to {speech_file_path}")


        # Play the generated speech file
        playsound(speech_file_path)

    except Exception as ex:
        print(ex)

if __name__ == "__main__":
    main()